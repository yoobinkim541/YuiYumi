const $ = (s, r = document) => r.querySelector(s);
const $$ = (s, r = document) => [...r.querySelectorAll(s)];
const reduceMotion = matchMedia("(prefers-reduced-motion: reduce)").matches;

let lang = "ja";
let bubbleIndex = 0;

function detectLang() {
  const saved = localStorage.getItem("yy-lang");
  if (saved && I18N[saved]) return saved;
  const n = (navigator.language || "ja").toLowerCase();
  if (n.startsWith("ko")) return "ko";
  if (/^zh-(cn|sg|hans)/.test(n)) return "zh-cn";
  if (n.startsWith("zh")) return "zh";
  return "ja";
}

function setBubble() {
  const el = $("#bubble");
  const text = I18N[lang].bubbles[bubbleIndex % I18N[lang].bubbles.length];
  el.textContent = "";
  text.split("\n").forEach((line, i) => {
    if (i) el.appendChild(document.createElement("br"));
    el.appendChild(document.createTextNode(line));
  });
}

function applyLang(next) {
  lang = next;
  const dict = I18N[lang];
  document.documentElement.lang = { zh: "zh-Hant", "zh-cn": "zh-Hans" }[lang] || lang;
  document.title = dict.title;
  $$("[data-i18n]").forEach((el) => { if (dict[el.dataset.i18n] != null) el.textContent = dict[el.dataset.i18n]; });
  $$("[data-i18n-html]").forEach((el) => { if (dict[el.dataset.i18nHtml] != null) el.innerHTML = dict[el.dataset.i18nHtml]; });
  $("#lang").value = lang;
  localStorage.setItem("yy-lang", lang);
  setBubble();
}

function toast(message) {
  const el = $("#toast");
  el.textContent = message;
  el.hidden = false;
  clearTimeout(toast.t);
  toast.t = setTimeout(() => { el.hidden = true; }, 1800);
}

function setupAppLink() {
  const url = (document.querySelector('meta[name="app-url"]')?.content || "").trim();
  const note = $("#appNote");
  if (url) {
    $$(".js-app").forEach((a) => { a.href = url; });
    note.hidden = true;
  } else {
    $("#appLink").setAttribute("aria-disabled", "true");
    $("#appLink").addEventListener("click", (e) => e.preventDefault());
  }
}

function setupPetals() {
  if (reduceMotion) return;
  const box = $(".petals");
  for (let i = 0; i < 14; i++) {
    const p = document.createElement("span");
    p.className = "petal";
    p.style.left = `${Math.random() * 110}%`;
    p.style.animationDuration = `${16 + Math.random() * 14}s`;
    p.style.animationDelay = `${-Math.random() * 30}s`;
    p.style.opacity = String(0.35 + Math.random() * 0.45);
    p.style.transform = `scale(${0.6 + Math.random() * 0.9})`;
    box.appendChild(p);
  }
}

function setupCharacter() {
  const stage = $("#stage");
  const root = $("#character");
  if (!reduceMotion) {
    let raf = 0, nx = 0, ny = 0;
    addEventListener("pointermove", (e) => {
      nx = (e.clientX / innerWidth - 0.5) * 2;
      ny = (e.clientY / innerHeight - 0.5) * 2;
      if (raf) return;
      raf = requestAnimationFrame(() => {
        raf = 0;
        root.style.setProperty("--dx", `${(nx * 10).toFixed(1)}px`);
        root.style.setProperty("--dy", `${(ny * 6).toFixed(1)}px`);
        root.style.setProperty("--rot", `${(nx * 1.6).toFixed(2)}deg`);
      });
    }, { passive: true });
  }
  stage.addEventListener("click", () => {
    bubbleIndex += 1;
    const b = $("#bubble");
    b.classList.remove("is-swap");
    void b.offsetWidth;
    b.classList.add("is-swap");
    setBubble();
  });
}

document.addEventListener("DOMContentLoaded", () => {
  $("#lang").addEventListener("change", (e) => applyLang(e.target.value));
  $("#useDraft").addEventListener("click", async () => {
    const text = $("#draftText").innerText.trim();
    try { await navigator.clipboard.writeText(text); toast(I18N[lang].toastCopied); }
    catch { toast(I18N[lang].toastFailed); }
  });
  applyLang(detectLang());
  setupAppLink();
  setupPetals();
  setupCharacter();
});
